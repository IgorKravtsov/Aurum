//! `/api/docs`, `/api/redoc`, `/api/openapi.json` — same URLs and same HTML
//! as FastAPI (`docs_url`/`redoc_url`/`openapi_url` in main.py).
//!
//! Docs live under /api/* because nginx only proxies that prefix to the
//! backend (see frontend/nginx.conf) — everything else falls through to the
//! SPA's index.html, which is why the defaults (/docs, /openapi.json) would
//! silently 404 through the reverse proxy. All three go away together when
//! AURUM_ENABLE_DOCS=false — leaving openapi.json reachable would keep
//! handing out the full API map even with the Swagger UI itself switched off.
//!
//! The pages load Swagger UI / ReDoc from the jsDelivr CDN exactly like
//! FastAPI's `get_swagger_ui_html` / `get_redoc_html`, so nothing is bundled
//! into the binary. The OpenAPI document is generated by utoipa from the
//! `#[utoipa::path]` annotations on the handlers; it describes the same
//! paths but is not byte-identical to FastAPI's.

use std::sync::Arc;

use axum::Router;
use axum::http::{HeaderValue, header};
use axum::response::{Html, IntoResponse, Response};
use axum::routing::get;

pub const OPENAPI_URL: &str = "/api/openapi.json";
pub const DOCS_URL: &str = "/api/docs";
pub const REDOC_URL: &str = "/api/redoc";

const TITLE: &str = "Aurum API";

fn swagger_html() -> String {
    format!(
        r##"
    <!DOCTYPE html>
    <html>
    <head>
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <link type="text/css" rel="stylesheet" href="https://cdn.jsdelivr.net/npm/swagger-ui-dist@5/swagger-ui.css">
    <link rel="shortcut icon" href="https://fastapi.tiangolo.com/img/favicon.png">
    <title>{TITLE} - Swagger UI</title>
    </head>
    <body>
    <div id="swagger-ui">
    </div>
    <script src="https://cdn.jsdelivr.net/npm/swagger-ui-dist@5/swagger-ui-bundle.js"></script>
    <!-- `SwaggerUIBundle` is now available on the page -->
    <script>
    const ui = SwaggerUIBundle({{
        url: '{OPENAPI_URL}',
    "dom_id": "#swagger-ui",
"layout": "BaseLayout",
"deepLinking": true,
"showExtensions": true,
"showCommonExtensions": true,
oauth2RedirectUrl: window.location.origin + '/docs/oauth2-redirect',
    presets: [
        SwaggerUIBundle.presets.apis,
        SwaggerUIBundle.SwaggerUIStandalonePreset
        ],
    }})
    </script>
    </body>
    </html>
    "##
    )
}

fn redoc_html() -> String {
    format!(
        r##"
    <!DOCTYPE html>
    <html>
    <head>
    <title>{TITLE} - ReDoc</title>
    <!-- needed for adaptive design -->
    <meta charset="utf-8"/>
    <meta name="viewport" content="width=device-width, initial-scale=1">
    
    <link href="https://fonts.googleapis.com/css?family=Montserrat:300,400,700|Roboto:300,400,700" rel="stylesheet">
    
    <link rel="shortcut icon" href="https://fastapi.tiangolo.com/img/favicon.png">
    <!--
    ReDoc doesn't change outer page styles
    -->
    <style>
      body {{
        margin: 0;
        padding: 0;
      }}
    </style>
    </head>
    <body>
    <noscript>
        ReDoc requires Javascript to function. Please enable it to browse the documentation.
    </noscript>
    <redoc spec-url="{OPENAPI_URL}"></redoc>
    <script src="https://cdn.jsdelivr.net/npm/redoc@2/bundles/redoc.standalone.js"> </script>
    </body>
    </html>
    "##
    )
}

/// The three docs routes, ready to merge into the app router.
pub fn router<S: Clone + Send + Sync + 'static>(openapi: utoipa::openapi::OpenApi) -> Router<S> {
    let spec: Arc<String> = Arc::new(openapi.to_json().unwrap_or_else(|_| "{}".into()));
    let swagger = swagger_html();
    let redoc = redoc_html();
    Router::new()
        .route(
            OPENAPI_URL,
            get(move || {
                let spec = spec.clone();
                async move { json_response(spec.as_str().to_owned()) }
            }),
        )
        .route(
            DOCS_URL,
            get(move || {
                let html = swagger.clone();
                async move { Html(html) }
            }),
        )
        .route(
            REDOC_URL,
            get(move || {
                let html = redoc.clone();
                async move { Html(html) }
            }),
        )
}

fn json_response(body: String) -> Response {
    let mut response = body.into_response();
    response.headers_mut().insert(header::CONTENT_TYPE, HeaderValue::from_static("application/json"));
    response
}
